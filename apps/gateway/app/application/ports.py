from datetime import datetime
from typing import Protocol

from apps.gateway.app.application.models import BufferedEvent, EventBufferHealth
from contracts.v2 import GatewayEnvelope, Presence, PresenceHealth


class BackendSender(Protocol):
    async def send(self, envelope: GatewayEnvelope) -> None: ...


class EventUplink(BackendSender, Protocol):
    status: PresenceHealth


class AgentConnections(Protocol):
    async def send(self, agent_id: str, message: str) -> bool: ...
    async def touch(self, agent_id: str) -> None: ...
    async def list_connected(self) -> tuple[str, ...]: ...
    async def last_seen(self, agent_id: str) -> datetime | None: ...


class PresenceRepository(Protocol):
    async def put(self, presence: Presence) -> None: ...
    async def get(self, agent_id: str) -> Presence | None: ...


class EventStore(Protocol):
    def put(self, envelope: GatewayEnvelope, *, now: datetime | None = None) -> bool: ...
    def due(self, now: datetime, limit: int) -> tuple[BufferedEvent, ...]: ...
    def mark_in_flight(self, event_id: str, next_attempt_at: datetime) -> None: ...
    def schedule_retry(self, event_id: str, next_attempt_at: datetime, error: str) -> None: ...
    def complete(self, event_id: str, at: datetime) -> None: ...
    def mark_terminal(self, event_id: str, error: str) -> None: ...
    def health(self, now: datetime | None = None) -> EventBufferHealth: ...


class EventDelivery(Protocol):
    def note_buffered(self, inserted: bool) -> None: ...
    def wake(self) -> None: ...
    async def handle_receipt(self, envelope: GatewayEnvelope) -> None: ...


class PresenceRefresher(Protocol):
    async def refresh_presence(self, stale_seconds: float, offline_seconds: float) -> None: ...
